-- Kepz — เอายอดเงินตัวอักษร เช่น (หนึ่งพันหกร้อยบาทถ้วน) ออกจากแม่แบบสัญญาที่บันทึกไว้
-- วิธีใช้: รันใน Supabase > SQL Editor (รันครั้งเดียว รันซ้ำได้ไม่มีผลเสีย)
-- ถ้ายังไม่เคยกดบันทึกแม่แบบ ไม่ต้องรันไฟล์นี้ก็ได้
-- =====================================================================
update public.settings
set contract_template_storage = regexp_replace(
      contract_template_storage,
      '\s*\(\{(ค่าเช่า|ค่าเช่าต่องวด|เงินประกัน|ค่าเช่าล่วงหน้า|ชำระแรกเข้ารวม)ตัวอักษร\}\)', '', 'g'),
    contract_template_parking = regexp_replace(
      contract_template_parking,
      '\s*\(\{(ค่าเช่า|ค่าเช่าต่องวด|เงินประกัน|ค่าเช่าล่วงหน้า|ชำระแรกเข้ารวม)ตัวอักษร\}\)', '', 'g')
where id = 1;
